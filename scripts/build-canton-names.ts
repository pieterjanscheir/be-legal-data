/**
 * Generates src/canton-names.generated.ts: each canton's id, name, number and validity from
 * data/cantons.json, the fields `formatCourtName` needs. The courts entry point imports this
 * file, not the cantons data, so it doesn't carry every canton's territory text. Run with
 * `pnpm build:canton-names`; `pnpm check` fails when the committed file is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs'

interface Canton {
    id: string
    name: { nl: string; fr: string }
    number?: number
    validFrom?: string
    validTo?: string
}

const cantons = JSON.parse(readFileSync('data/cantons.json', 'utf8')) as Canton[]
const str = (value: string) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`

let out = `// Generated by scripts/build-canton-names.ts from data/cantons.json. Do not edit.
import type { Bilingual } from './common'
import type { CantonId } from './ids.generated'
import type { Validity } from './time'

/** The fields of a canton that court labels use */
export interface CantonName extends Validity {
    id: CantonId
    name: Bilingual
    number?: number
}

export const cantonNames: readonly CantonName[] = [
`
for (const { id, name, number, validFrom, validTo } of cantons) {
    const fields = [`id: ${str(id)}`, `name: { nl: ${str(name.nl)}, fr: ${str(name.fr)} }`]
    if (number !== undefined) fields.push(`number: ${number}`)
    if (validFrom !== undefined) fields.push(`validFrom: ${str(validFrom)}`)
    if (validTo !== undefined) fields.push(`validTo: ${str(validTo)}`)
    out += `    { ${fields.join(', ')} },\n`
}
out += ']\n'
writeFileSync('src/canton-names.generated.ts', out)
