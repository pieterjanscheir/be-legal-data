/**
 * Generates src/ids.generated.ts: a union type of the ids in each data file, so ids are checked
 * and autocompleted at compile time. Run with `pnpm build:ids`; `pnpm check` fails when the
 * committed file is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const files = {
    JudicialAreaId: 'judicial-areas',
    ArrondissementId: 'arrondissements',
    CantonId: 'cantons',
    MunicipalityId: 'municipalities',
    CourtId: 'courts',
    PrisonId: 'prisons',
    HouseOfJusticeId: 'houses-of-justice',
    PostalCodeId: 'postal-codes',
} as const

let out = '// Generated by scripts/build-ids.ts from data/. Do not edit.\n'
for (const [type, file] of Object.entries(files)) {
    const records = JSON.parse(readFileSync(`data/${file}.json`, 'utf8')) as { id: string }[]
    const ids = records.map((record) => record.id)
    out += `\n/** Id of a record in data/${file}.json */\nexport type ${type} =\n`
    out +=
        [...ids]
            .sort()
            .map((id) => `    | '${id}'`)
            .join('\n') + '\n'
}
writeFileSync('src/ids.generated.ts', out)
